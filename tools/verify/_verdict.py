"""验证工具的退出码 —— **唯一定义**。

为什么这需要一个共享模块
------------------------
红线 R-3 是 `UNKNOWN ≠ PASS`。工具们在**打印**上早就照做了
（「🔶 判不了」到处都是），但退出码是各写一遍的裸数字。

外部深度评审在 `latency_report.py` 上点出了后果：读不到运行时数据退 `1`，
和「Stage 1 真的串行了」同一个码。顺着这条线扫一遍，同形状**一共四处**：

==========================  ====================================
`latency_report.py`         读不到轮次 / 找不到决策 → `1`
`agent_trace.py`            一个 agent 库都没有 → `1`
`missing_ledger.py`         库里一张卡都没有 → `1`
`phase1_acceptance.py`      **PENDING 塌进 FAIL 码**
==========================  ====================================

最后那一处最说明问题：它上面一行注释写着
「🔴 PENDING 不算 PASS。这条是本项目的第一条红线」，
下一行 `return 0 if … else 1` —— **把 PENDING 和 FAIL 退成了同一个码**。

> 🔴 三态在**每一层**都要是三态。
> 渲染层做对了、调用层塌回两态，等于没做 —— 因为最常见的读法是
> 「跑完没报错就是过了」，读的正是退出码。

⇒ 口径搬到这里，五个工具 `from _verdict import …`。
  排查方向从此可以只看一个数字：`2` 去查数据，`1` 去查代码。

覆盖什么 / 不覆盖什么
---------------------
- 覆盖：`tools/verify/` 下工具**进程退出码**的含义
- **不覆盖**：`AgentVerdict.verdict` 那套业务判定（`PASS`/`WARNING`/`FAIL`）
  —— 名字像，是两个层的东西。契约层那套在 `skills/_contract/`
"""

from __future__ import annotations

__all__ = ["PASS", "FAIL", "UNKNOWN", "describe"]

#: 查了，没问题。
PASS = 0

#: 查了，**真的不对**。去看代码 / 配置。
#: ⚠️ 只有在「确实观察到了违规」时才用它。观察不到不算不对。
FAIL = 1

#: **没查成**。去看数据源 / 环境 / 时机，不要去改代码。
#: 🔴 这个码存在的全部意义，就是让人别把「没验到」读成「验过了」。
UNKNOWN = 2


def describe(code: int) -> str:
    """把退出码写成人话 —— 报错要指路。"""
    return {
        PASS: "通过",
        FAIL: "不通过（确实观察到了违规）",
        UNKNOWN: "判不了（没查成，先看数据与时机，别改代码）",
    }.get(code, f"未定义的退出码 {code}")
